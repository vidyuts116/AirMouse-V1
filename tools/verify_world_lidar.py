#!/usr/bin/env python3
"""Verify AirMouse LiDAR ranges in Phase 2 worlds against exact 2D ray casting.

For each world generated by tools/make_maze.py: check the world was generated
from the current baseline, boot it, let the vehicle settle, record 2 s of
scans, and compare every beam with a slab ray cast against the wall boxes in
the world's JSON sidecar (from the vehicle's measured rest pose). Stops at the
first FAIL. Never edits any SDF.
"""

import argparse
import hashlib
import importlib.util
import json
import math
import os
import shutil
import subprocess
import sys
import tempfile
import time
import warnings
import xml.etree.ElementTree as ET
from datetime import date
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
WORLDS = ROOT / "simulation" / "worlds"
ORDER = ["empty", "wall", "corridor", "junction", "room", "small_maze", "nidar_maze"]


def all_worlds():
    variants = sorted((p.stem for p in WORLDS.glob("nidar_maze_s*.json")), key=lambda n: int(n.rsplit("_s", 1)[1]))
    return ORDER + variants


def load(name):
    path = Path(__file__).with_name(name)
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


reg = load("airmouse_regression.py")
warnings.filterwarnings("ignore", category=RuntimeWarning)  # nanmean/subtract on all-no-return beams


def lidar_config():
    lidar = [s for s in reg.sensors_in(reg.BASELINE) if s["type"] in ("gpu_lidar", "lidar") and reg.beams(s) > 1][0]
    el = lidar["el"]
    return {"topic": lidar["topic"], "rate": lidar["rate"], "sigma": float(el.findtext("lidar/noise/stddev")),
            "rmin": float(el.findtext("lidar/range/min")), "rmax": float(el.findtext("lidar/range/max")),
            "z": [float(v) for v in el.findtext("pose").split()][2] if el.findtext("pose") else 0.0}


def ray_cast(ox, oy, angles, walls, rmin, rmax):
    """Nearest hit distance per beam against axis-aligned boxes; inf if none within [rmin, rmax]."""
    if not walls:
        return np.full(len(angles), np.inf)
    w = np.array(walls, dtype=float)
    xmin, xmax = w[:, 0] - w[:, 2] / 2, w[:, 0] + w[:, 2] / 2
    ymin, ymax = w[:, 1] - w[:, 3] / 2, w[:, 1] + w[:, 3] / 2
    dx, dy = np.cos(angles)[:, None], np.sin(angles)[:, None]
    with np.errstate(divide="ignore", invalid="ignore"):
        tx1, tx2 = (xmin - ox) / dx, (xmax - ox) / dx
        ty1, ty2 = (ymin - oy) / dy, (ymax - oy) / dy
    # Rays parallel to an axis: inside the slab -> (-inf, inf), outside -> no hit.
    inx = (ox >= xmin) & (ox <= xmax)
    iny = (oy >= ymin) & (oy <= ymax)
    tx_lo = np.where(dx == 0, np.where(inx, -np.inf, np.inf), np.minimum(tx1, tx2))
    tx_hi = np.where(dx == 0, np.where(inx, np.inf, -np.inf), np.maximum(tx1, tx2))
    ty_lo = np.where(dy == 0, np.where(iny, -np.inf, np.inf), np.minimum(ty1, ty2))
    ty_hi = np.where(dy == 0, np.where(iny, np.inf, -np.inf), np.maximum(ty1, ty2))
    t_enter, t_exit = np.maximum(tx_lo, ty_lo), np.minimum(tx_hi, ty_hi)
    hit = (t_exit >= t_enter) & (t_exit > 0)
    t = np.where(hit, np.maximum(t_enter, 0.0), np.inf).min(axis=1)
    return np.where((t >= rmin) & (t <= rmax), t, np.inf)


def verify(ctx, name):
    log = ctx.log
    sdf, meta_path = WORLDS / f"{name}.sdf", WORLDS / f"{name}.json"
    log.stage(ORDER.index(name) if name in ORDER else 99, f"World {name}")
    meta = json.loads(meta_path.read_text())
    sha = hashlib.sha256(reg.BASELINE.read_bytes()).hexdigest()
    ok = log.check(name, "generated from current baseline", meta["baseline_sha256"] == sha,
                   meta["baseline_sha256"][:16] + "…", sha[:16] + "…", "OBSERVED")
    r = subprocess.run([ctx.gz, "sdf", "-k", str(sdf)], text=True, capture_output=True)
    ok &= log.check(name, "gz sdf -k", "Valid" in r.stdout, (r.stdout or r.stderr).strip().splitlines()[-1],
                    "Valid.", "OBSERVED")
    if not ok:
        return False
    # Structure: collisions only on wall boxes; launch pad and survivor markers are visual-only.
    root = ET.parse(sdf).getroot()
    models = {m.get("name"): m for m in root.iter("model")}
    if "maze" in models:
        ncol = len(list(models["maze"].iter("collision")))
        ok &= log.check(name, "maze collisions = wall boxes", ncol == len(meta["walls_cx_cy_lx_ly"]),
                        ncol, len(meta["walls_cx_cy_lx_ly"]), "OBSERVED")
    extra = [n for n in models if n == "launch_pad" or n.startswith("survivor_")]
    if extra:
        colliding = [n for n in extra if list(models[n].iter("collision"))]
        ok &= log.check(name, "launch pad + survivor markers non-colliding (visual only)", not colliding,
                        f"{len(extra)} models, colliding: {colliding or 'none'}", "none colliding", "OBSERVED")
        pad = models.get("launch_pad")
        if pad is not None:
            size = [float(v) for v in pad.find(".//box/size").text.split()]
            log.info(name, "launch pad", f"{size[0]:g} x {size[1]:g} m at ({pad.findtext('pose')}); spawn "
                     f"({meta['spawn']['x']:g}, {meta['spawn']['y']:g})", "OBSERVED")
    if not ok:
        return False
    cfg = ctx.lidar
    session = reg.Session(ctx.gz, ctx.helper, sdf, log, name)
    probe = None
    try:
        probe = reg.Probe(ctx.probe, [f"scan:{cfg['topic']}"], log.dir / f"{name}_probe.txt")
        views = []

        def capture(view, target=None):
            if target is not None:
                session._call(f"set_pose {view}", lambda: reg.diag.service(
                    ctx.gz, reg.SET_POSE, "gz.msgs.Pose", f'name: "airmouse", position: {{x: {target[0]}, '
                    f'y: {target[1]}, z: 0.1}}, orientation: {{x: 0, y: 0, z: 0, w: 1}}'))
            while True:
                rest = session.wait_rest()
                if target is None or math.hypot(rest[1] - target[0], rest[2] - target[1]) < 0.05:
                    break
                time.sleep(0.1)
            session.wait_pose(lambda p: p[0] >= rest[0] + 2.0, 40, f"2 s of scans at rest ({view})")
            time.sleep(0.3)
            with probe.lock:
                views.append((view, rest, [(h, rr) for h, rr in probe.scan.get(cfg["topic"], [])
                                           if rest[0] <= h[0] <= rest[0] + 2.0]))

        capture("start")
        rooms = meta.get("params", {}).get("rooms") or []
        if rooms and meta.get("markers_cx_cy_lx_ly"):
            cx, cy = rooms[0]["centre"]
            capture("room0, 0.9 m east of its marker", (cx + 0.9, cy))
        with probe.lock:
            all_stamps = [h[0] for h, _ in probe.scan.get(cfg["topic"], [])]
    finally:
        if probe:
            probe.stop()
        session.close()
    rate, span = reg.rate_of(all_stamps)
    ok &= log.check(name, "LiDAR rate (sim time)", abs(rate - cfg["rate"]) <= 0.1 * cfg["rate"],
                    f"{rate:.2f} Hz over {span:.2f} s", f"{cfg['rate']:g} Hz ±10 %", "OBSERVED")

    def analyse(view, rest, scans):
        tag = f"{name} [{view}]"
        ok = True
        if not scans:
            return log.check(tag, "scans at rest", False, 0, "> 0", "OBSERVED"), None
        x, y, qx, qy, qz, qw = rest[1], rest[2], rest[4], rest[5], rest[6], rest[7]
        yaw = math.atan2(2 * (qw * qz + qx * qy), 1 - 2 * (qy * qy + qz * qz))
        spawn = meta["spawn"]
        log.info(tag, "vehicle rest pose", f"x {x:+.4f}, y {y:+.4f}, z {rest[3]:.4f} m, yaw {math.degrees(yaw):+.3f} deg "
                 f"(spawn {spawn['x']:g}, {spawn['y']:g}); {len(meta['walls_cx_cy_lx_ly'])} wall boxes", "OBSERVED")
        obstacles = meta["walls_cx_cy_lx_ly"] + meta.get("markers_cx_cy_lx_ly", [])
        h0 = scans[0][0]
        beam = h0[2] + h0[3] * np.arange(len(scans[0][1]))
        ranges = np.array([rr for _, rr in scans])
        ranges[~np.isfinite(ranges)] = np.inf
        expected = ray_cast(x, y, beam + yaw, obstacles, cfg["rmin"], cfg["rmax"])
        # Beam-angle tolerance: at grazing incidence range is very sensitive to angle (dr/dtheta = r*cot(incidence)),
        # so each beam is compared with the ray-cast band over +/- half a beam step.
        delta = 0.5 * abs(h0[3])
        band = np.stack([ray_cast(x, y, beam + yaw + o, obstacles, cfg["rmin"], cfg["rmax"])
                         for o in np.linspace(-delta, delta, 21)])
        lo, hi = band.min(axis=0), band.max(axis=0)
        any_inf = ~np.isfinite(band).all(axis=0)
        finite_frac = np.isfinite(ranges).mean(axis=0)
        meas = np.where(finite_frac >= 0.5, np.nanmean(np.where(np.isfinite(ranges), ranges, np.nan), axis=0), np.inf)
        match = ((np.isfinite(meas) & np.isfinite(lo) & (meas >= lo - 0.05) & (meas <= hi + 0.05))
                 | (~np.isfinite(meas) & any_inf))
        frac = match.mean()
        ok &= log.check(tag, "beams within ray-cast band (±half beam step, ±5 cm; or no-return)", frac >= 0.98,
                        f"{match.sum()}/{len(match)} = {frac * 100:.1f} % ({int(np.isfinite(expected).sum())} beams expect a "
                        f"return; band ±{math.degrees(delta):.2f} deg)", ">= 98 % (ANALYTICAL ray cast vs OBSERVED)", "OBSERVED")
        # Implied beam-angle error: offset (within +/-3 deg) whose ray cast best explains each finite measurement.
        offs = np.radians(np.linspace(-3, 3, 601))
        fine = np.stack([ray_cast(x, y, beam + yaw + o, obstacles, cfg["rmin"], cfg["rmax"]) for o in offs])
        fin = np.isfinite(meas)
        if fin.any():
            diff = np.abs(np.where(np.isfinite(fine[:, fin]), fine[:, fin], 1e9) - meas[fin])
            implied = np.degrees(offs[np.argmin(diff, axis=0)])
            sens = (hi - lo)[fin] / 2
            steep = sens > 0.05
            log.info(tag, "implied beam-angle error (finite returns)",
                     f"all: median |off| {np.median(np.abs(implied)):.2f} deg; grazing beams (band > ±5 cm, n={int(steep.sum())}): "
                     f"max |off| {np.abs(implied[steep]).max() if steep.any() else 0:.2f} deg", "INFERRED")
        bad = np.where(~match)[0]
        if len(bad):
            log.info(tag, "beams outside band (deg: measured / band m)",
                     ", ".join(f"{math.degrees(beam[i]):+.0f}: {meas[i]:.3f}/{lo[i]:.3f}-{hi[i]:.3f}" for i in bad[:12])
                     + (" …" if len(bad) > 12 else ""), "OBSERVED")
        well = np.isfinite(meas) & np.isfinite(hi) & ((hi - lo) / 2 <= 0.01)
        err = meas - expected
        np.savetxt(log.dir / f"{name}_{view}_beams.csv",
                   np.column_stack([np.degrees(beam), meas, expected, lo, hi, finite_frac, match, well]), delimiter=",",
                   fmt="%.6g", header="beam_deg,measured_mean_m,expected_m,band_lo_m,band_hi_m,finite_fraction,match,"
                   "well_conditioned", comments="")
        good = well
        if good.any():
            bias = float(err[good].mean())
            ok &= log.check(tag, "range bias, well-conditioned beams (band <= ±1 cm)", abs(bias) <= 0.005,
                            f"{bias * 1e3:+.2f} mm (n={int(good.sum())} beams, max |err| {np.abs(err[good]).max() * 1e3:.1f} mm)",
                            "|bias| <= 5 mm", "OBSERVED")
            single = (ranges[:, good] - expected[good])
            noise = float(np.std(single[np.isfinite(single)]))
            ok &= log.check(tag, "single-scan noise / configured sigma (well-conditioned beams)",
                            0.5 <= noise / cfg["sigma"] <= 2.0,
                            f"{noise * 1e3:.2f} mm / {cfg['sigma'] * 1e3:.0f} mm = {noise / cfg['sigma']:.2f}", "0.5-2.0",
                            "OBSERVED")
        else:
            log.info(tag, "range bias / noise", "no well-conditioned returns expected (open world)", "OBSERVED")
        if "marker" in view:
            west = int(np.argmin(np.abs(np.angle(np.exp(1j * (beam + yaw - math.pi))))))
            ok &= log.check(tag, "survivor marker seen by LiDAR (beam toward marker, face 0.70 m)",
                            np.isfinite(meas[west]) and abs(meas[west] - 0.70) <= 0.05,
                            f"{meas[west]:.4f} m at {math.degrees(beam[west]):+.1f} deg", "0.70 ± 0.05 m (ANALYTICAL)",
                            "OBSERVED")
        return ok, (match, bias if good.any() else None, noise if good.any() else None)

    results = [analyse(view, r, sc) for view, r, sc in views]
    ok &= all(v for v, _ in results)
    match, bias, noise = results[0][1] if results[0][1] else (np.array([False]), None, None)
    ctx.rows.append((name, "PASS" if ok else "FAIL", len(meta["walls_cx_cy_lx_ly"]),
                     " + ".join(f"{int(r[1][0].sum())}/{len(r[1][0])}" for r in results if r[1]),
                     f"{bias * 1e3:+.2f} mm" if bias is not None else "—",
                     f"{noise * 1e3:.1f} mm" if noise is not None else "—", f"{rate:.2f} Hz"))
    return ok


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("worlds", nargs="+", help="world names (see simulation/worlds/*.json) or all")
    parser.add_argument("--logdir", default=str(ROOT / "logs" / f"phase2-{date.today().isoformat()}"))
    args = parser.parse_args()
    os.environ.setdefault("GZ_IP", "127.0.0.1")

    class Ctx:
        pass

    ctx = Ctx()
    ctx.log = reg.Log(Path(args.logdir))
    ctx.rows = []
    ctx.gz = reg.gz_bin()
    ctx.lidar = lidar_config()
    tmp = tempfile.TemporaryDirectory(prefix="airmouse-phase2-")
    ctx.helper, ctx.probe = Path(tmp.name) / "helper", Path(tmp.name) / "probe"
    reg.diag.compile_publisher(reg.TOOLS / "airmouse_hover_helper.cc", ctx.helper)
    reg.diag.compile_publisher(reg.TOOLS / "airmouse_sensor_probe.cc", ctx.probe)
    if reg.gz_sim_processes():
        raise SystemExit("a gz sim process is already running; stop it first")
    failed = None
    try:
        for name in (all_worlds() if "all" in args.worlds else args.worlds):
            if not verify(ctx, name):
                failed = name
                break
    except (reg.StageFail, RuntimeError, OSError, subprocess.SubprocessError) as error:
        ctx.log(f"  [FAIL] aborted: {error}")
        failed = failed or "abort"
    finally:
        tmp.cleanup()
        ctx.log(f"\nCleanup: gz sim processes left = {len(reg.gz_sim_processes())}; GZ_IP={os.environ['GZ_IP']}")
    ctx.log("\n| World | Result | Wall boxes | Beams matching | Range bias | Single-scan noise | LiDAR rate |")
    ctx.log("|---|---|---|---|---|---|---|")
    for row in ctx.rows:
        ctx.log("| " + " | ".join(str(v) for v in row) + " |")
    ctx.log(f"\nOVERALL: {'PASS' if failed is None else f'FAIL at {failed}'}")
    return 0 if failed is None else 1


if __name__ == "__main__":
    sys.exit(main())
