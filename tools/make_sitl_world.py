#!/usr/bin/env python3
"""Generate an ArduPilot SITL world from an AirMouse world (baseline or Phase 2 world).

Injects into the `airmouse` model, without touching any physics:
  * ArduPilotPlugin (ardupilot_gazebo, JSON/UDP 9002, lock-step) with COMMAND channels
  * airmouse::ActuatorsBridge (src/airmouse_sitl_bridge): Doubles -> gz.msgs.Actuators
  * a diagnostic JointStatePublisher (/airmouse/diagnostic/joint_state, 200 Hz) for motor tests
and moves the IMU from /airmouse/imu to its default scoped topic, which ArduPilotPlugin requires.

Motor map (ArduPilot FRAME_CLASS=1 Quad, FRAME_TYPE=18 BF_X_REV; verified against
Copter-4.6.3 libraries/AP_Motors/AP_MotorsMatrix.cpp:639-650):
  SERVO1 (M1, 135 deg, back-right,  CCW) -> rotor_2 (actuator 2, ccw)
  SERVO2 (M2,  45 deg, front-right, CW ) -> rotor_3 (actuator 3, cw)
  SERVO3 (M3, -135 deg, back-left,  CW ) -> rotor_1 (actuator 1, cw)
  SERVO4 (M4, -45 deg, front-left,  CCW) -> rotor_0 (actuator 0, ccw)
PWM 1000-2000 us maps linearly to 0-800 rad/s (= maxRotVelocity).
"""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SERVO_TO_ROTOR = {1: 2, 2: 3, 3: 1, 4: 0}
PWM_MIN, PWM_MAX, OMEGA_MAX = 1000, 2000, 800.0


def sitl_block():
    controls = []
    for servo, rotor in SERVO_TO_ROTOR.items():
        controls.append(
            f'        <control channel="{servo - 1}"><!-- SERVO{servo} -> rotor_{rotor} -->'
            f"<jointName>rotor_{rotor}_joint</jointName><type>COMMAND</type>"
            f"<cmd_topic>/airmouse/sitl/rotor_{rotor}_cmd</cmd_topic>"
            f"<multiplier>{OMEGA_MAX:g}</multiplier><offset>0</offset>"
            f"<servo_min>{PWM_MIN}</servo_min><servo_max>{PWM_MAX}</servo_max></control>\n")
    inputs = "".join(f"<input_topic>/airmouse/sitl/rotor_{r}_cmd</input_topic>" for r in range(4))
    return (
        "      <!-- ArduPilot SITL interface (generated by tools/make_sitl_world.py). No physics parameters. -->\n"
        '      <plugin filename="ArduPilotPlugin" name="ArduPilotPlugin">\n'
        "        <fdm_addr>127.0.0.1</fdm_addr><fdm_port_in>9002</fdm_port_in>\n"
        "        <connectionTimeoutMaxCount>5</connectionTimeoutMaxCount><lock_step>1</lock_step>"
        "<have_32_channels>0</have_32_channels>\n"
        '        <modelXYZToAirplaneXForwardZDown degrees="true">0 0 0 180 0 0</modelXYZToAirplaneXForwardZDown>\n'
        '        <gazeboXYZToNED degrees="true">0 0 0 180 0 90</gazeboXYZToNED>\n'
        "        <imuName>base_link::imu_sensor</imuName>\n"
        + "".join(controls) +
        "      </plugin>\n"
        '      <plugin filename="AirMouseActuatorsBridge" name="airmouse::ActuatorsBridge">'
        f"{inputs}<output_topic>/airmouse/gazebo/command/motor_speed</output_topic></plugin>\n"
        "      <!-- Diagnostic-only joint telemetry for motor tests. -->\n"
        '      <plugin filename="gz-sim-joint-state-publisher-system" name="gz::sim::systems::JointStatePublisher">'
        "<topic>/airmouse/diagnostic/joint_state</topic><update_rate>200</update_rate>"
        + "".join(f"<joint_name>rotor_{r}_joint</joint_name>" for r in range(4)) + "</plugin>\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("world", nargs="?", default=str(ROOT / "simulation" / "worlds" / "empty.sdf"))
    parser.add_argument("--out", default=str(ROOT / "simulation" / "sitl"))
    args = parser.parse_args()
    src = Path(args.world)
    text = src.read_text()
    start = text.index('<model name="airmouse"')
    end = text.index("    </model>", start)       # closing tag of the airmouse model (4-space indent)
    assert text[start:end].count("<model") == 1, "unexpected nested model inside airmouse"
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    dst = out / f"{src.stem}_sitl.sdf"
    # ArduPilotPlugin subscribes to the IMU's DEFAULT scoped topic (scopedName(imu) + "/imu",
    # ardupilot_gazebo ArduPilotPlugin.cc:1165) and ignores a custom <topic>. In SITL worlds only, drop the
    # custom IMU topic so the IMU publishes where the plugin listens. Not a physics change.
    imu_topic = "<topic>/airmouse/imu</topic>"
    assert text.count(imu_topic) == 1, "expected exactly one custom IMU topic in the source world"
    out_text = text[:end] + sitl_block() + text[end:]
    out_text = out_text.replace(imu_topic, "<!-- IMU on default scoped topic for ArduPilotPlugin -->")
    dst.write_text(out_text)
    print(f"{dst.relative_to(ROOT)} from {src.relative_to(ROOT)} "
          f"(source sha256 {hashlib.sha256(src.read_bytes()).hexdigest()[:8]})")


if __name__ == "__main__":
    main()
